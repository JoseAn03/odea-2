function buildCampaign(config, chapterDefinitions) {
  let sequence = 0;
  return {
    ...config,
    chapters: chapterDefinitions.map((chapter) => ({
      ...chapter,
      missions: chapter.missions.map((definition) => ({
        id: `${config.id}-${String(++sequence).padStart(2, '0')}`,
        campaignId: config.id,
        chapterId: chapter.id,
        ...definition,
      })),
    })),
  };
}

